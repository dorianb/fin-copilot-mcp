DEFAULT_UNIVERSE = "cac40"


def resolve_universe(name: str | None, tickers: list[str] | None) -> list[str]:
    custom = _normalize_tickers(tickers or [])
    if custom:
        return custom
    key = (name or DEFAULT_UNIVERSE).strip().lower()
    if key not in UNIVERSES:
        known = ", ".join(sorted(UNIVERSES))
        raise ValueError(f"Univers inconnu: {name!r}. Univers disponibles: {known}")
    return list(UNIVERSES[key])


def _normalize_tickers(tickers: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for raw in tickers:
        ticker = raw.strip().upper()
        if not ticker or ticker in seen:
            continue
        seen.add(ticker)
        out.append(ticker)
    return out
